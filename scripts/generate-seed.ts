/**
 * Generates migrations/0002_seed.sql from the catalogue in constants.ts.
 * Run with: npx tsx scripts/generate-seed.ts
 */
import { writeFileSync } from 'node:fs';
import { MOCK_PRODUCTS } from '../constants';

const q = (v: unknown) =>
  v === undefined || v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;

const STOCK = { 'in-stock': 25, 'low-stock': 3, 'out-of-stock': 0, 'pre-order': 0 } as const;

const rows = MOCK_PRODUCTS.map((p) =>
  `(${[
    q(p.id), q(p.name), q(p.price), q(p.originalPrice), q(p.image), q(JSON.stringify(p.gallery ?? [])),
    q(p.category), q(p.team), q(p.league), q(p.type), q(p.isPlayerEdition ? 1 : 0),
    q(p.status === 'pre-order' ? 1 : 0), q(STOCK[p.status]), q(p.rating), q(p.reviews),
    q(p.description), q(p.season), q(p.color),
  ].join(', ')})`,
);

const sql = `-- Seed catalogue (generated by scripts/generate-seed.ts — do not edit by hand)
INSERT INTO products (id, name, price, original_price, image, gallery, category, team, league, type,
  is_player_edition, is_preorder, stock, rating, reviews, description, season, color) VALUES
${rows.join(',\n')};
`;
writeFileSync(new URL('../migrations/0002_seed.sql', import.meta.url), sql);
console.log(`Wrote ${rows.length} products to migrations/0002_seed.sql`);
